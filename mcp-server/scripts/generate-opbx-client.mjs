#!/usr/bin/env node
/**
 * Regenerate the OPBX OpenAPI TypeScript types.
 *
 * Source: ../docs/opbx-openapi/openapi.yaml (modular spec with relative $refs,
 * resolved by openapi-typescript's built-in redocly resolver).
 *
 * Usage: npm run generate:opbx-client
 * Re-run whenever the OPBX spec changes. Output is committed.
 */
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const spec = path.resolve(root, "../docs/opbx-openapi/openapi.yaml");
const out = path.join(root, "src/opbx/generated/schema.d.ts");

if (!fs.existsSync(spec)) {
  console.error(`OpenAPI spec not found at ${spec}`);
  process.exit(1);
}

const bin = path.join(root, "node_modules", ".bin", "openapi-typescript");
execFileSync(bin, [spec, "-o", out, "--export-type", "--alphabetize"], {
  stdio: "inherit",
});

const banner = `/* eslint-disable */\n/**\n * AUTO-GENERATED by scripts/generate-opbx-client.mjs from docs/opbx-openapi/openapi.yaml.\n * Do not edit by hand. Run \`npm run generate:opbx-client\` to regenerate.\n */\n`;
fs.writeFileSync(out, banner + fs.readFileSync(out, "utf8"));
console.log(`Generated ${out}`);
